#!/usr/bin/env python3
"""Apply Quickshell and Satty window opacity as Hyprland rules.

Usage:
  opacity.py get
  opacity.py set <quickshell 5-100> <satty 5-100>

100 is solid and adds no dimming rule. Fullscreen windows and the
Settings window stay solid when Quickshell dims other windows.
"""

import fcntl
import json
import os
import subprocess
import sys
import tempfile

STATE = os.environ.get("OPACITY_STATE", os.path.expanduser("~/.config/hypr/opacity.state"))
LUA = os.environ.get("OPACITY_LUA", os.path.expanduser("~/.config/hypr/opacity.lua"))
LOCK = os.environ.get("OPACITY_LOCK", os.path.expanduser("~/.config/hypr/opacity.lock"))


def valid(text):
    if not text.isdigit():
        return None
    number = int(text)
    if 5 <= number <= 100:
        return number
    return None


def read_state():
    quickshell = 100
    satty = 100
    try:
        with open(STATE, "r", encoding="utf-8") as handle:
            lines = handle.readlines()
    except OSError:
        return quickshell, satty
    for line in lines:
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        number = valid(value.strip())
        if number is None:
            continue
        if key.strip() == "quickshell":
            quickshell = number
        elif key.strip() == "satty":
            satty = number
    return quickshell, satty


def atomic_write(path, text):
    directory = os.path.dirname(path) or "."
    os.makedirs(directory, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=directory, prefix=".opacity-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(tmp, path)
    except Exception:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def levels(percent):
    text = f"{percent / 100:.2f}"
    return f"{text} override {text} override"


def lua_text(quickshell, satty):
    # Long brackets keep the regex backslash literal. A short Lua string
    # with one backslash before the dot is an invalid escape, and Hyprland
    # rejects the whole file. That is the Quickshell slider's error. Satty
    # already used a doubled backslash, so that slider loaded.
    lines = [
        "-- Generated by opacity.py. Loaded after the other window rules.",
        "-- 100 is solid and adds no dimming rule for that target.",
        "_G.QS_OPACITY = _G.QS_OPACITY or {}",
        "local function add(spec)",
        "    local rule = hl.window_rule(spec)",
        "    _G.QS_OPACITY[#_G.QS_OPACITY + 1] = rule",
        "end",
        "local function levels(pct)",
        "    local s = string.format('%.2f', pct / 100)",
        "    return s .. ' override ' .. s .. ' override'",
        "end",
    ]
    if quickshell < 100:
        lines.append(
            "add({ name = 'qs-opacity-apps', match = { class = '.*' }, opacity = levels(%d) })"
            % quickshell
        )
        lines.append(
            "add({ name = 'qs-opacity-settings', match = { class = [[^org\\.quickshell$]], title = [[^Settings$]] }, opacity = '1 override 1 override 1 override' })"
        )
        lines.append(
            "add({ name = 'qs-opacity-fullscreen', match = { fullscreen = true }, opacity = '1 override 1 override 1 override' })"
        )
    if satty < 100 or quickshell < 100:
        lines.append(
            "add({ name = 'qs-opacity-satty', match = { class = [[^com\\.gabm\\.satty$]] }, opacity = levels(%d) })"
            % satty
        )
    lines.append("")
    return "\n".join(lines)


def apply_live():
    signature = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE", "")
    if not signature:
        return
    snippet = (
        "if _G.QS_OPACITY then\n"
        "  for i = 1, #_G.QS_OPACITY do\n"
        "    local rule = _G.QS_OPACITY[i]\n"
        "    if rule then rule:set_enabled(false) end\n"
        "  end\n"
        "end\n"
        "_G.QS_OPACITY = {}\n"
        "dofile(%s)\n"
        "return 'ok'\n"
    ) % json.dumps(LUA)
    try:
        done = subprocess.run(
            ["hyprctl", "repl", snippet],
            check=False,
            capture_output=True,
            text=True,
            timeout=8,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        print(f"error: hyprctl repl failed: {exc}", file=sys.stderr)
        sys.exit(1)
    out = (done.stdout or "") + (done.stderr or "")
    if done.returncode != 0 or out.startswith("error:") or not out.strip():
        print(f"error: hyprctl repl failed: {out.strip() or 'no output'}", file=sys.stderr)
        sys.exit(1)


def cmd_set(quickshell, satty):
    os.makedirs(os.path.dirname(LOCK) or ".", exist_ok=True)
    with open(LOCK, "a", encoding="utf-8") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        atomic_write(STATE, f"quickshell={quickshell}\nsatty={satty}\n")
        atomic_write(LUA, lua_text(quickshell, satty))
        apply_live()
    print("ok")


def main():
    if len(sys.argv) < 2:
        print("usage: opacity.py get | set <quickshell> <satty>", file=sys.stderr)
        return 2
    command = sys.argv[1]
    if command == "get":
        quickshell, satty = read_state()
        print(f"quickshell={quickshell}")
        print(f"satty={satty}")
        return 0
    if command == "set":
        if len(sys.argv) != 4:
            print("usage: opacity.py set <quickshell> <satty>", file=sys.stderr)
            return 2
        quickshell = valid(sys.argv[2])
        satty = valid(sys.argv[3])
        if quickshell is None or satty is None:
            print("error: percents must be 5-100", file=sys.stderr)
            return 2
        cmd_set(quickshell, satty)
        return 0
    print("usage: opacity.py get | set <quickshell> <satty>", file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
